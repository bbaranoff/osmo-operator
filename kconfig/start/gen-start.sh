#!/bin/bash
# kconfig/start/gen-start.sh - the generated part of the start.sh menu
# =============================================================================
# Run by start.sh --configure before the menu, ON THE MACHINE THAT STARTS THE
# BENCH: the choices follow what was built and what is there.
#
#   Kconfig.build     BUILT_<X>  from the build .config embedded in the target
#                                (like /proc/config.gz), first found of:
#                                $OSMO_BUILD_CONFIG, /etc/osmocom/build.config,
#                                <repo>/.config ; none: everything counts as built
#                     HAVE_<X>   binaries / files present on this machine
#   Kconfig.runmods   RUN_MOD_<SLUG>  the modules of run.sh (qosmo run_modules/,
#                                MOD_REGISTER / MOD_DEPS) -> run.sh --skip
#   Kconfig.firmware  FW_APP_<X> the firmware apps really built
#                                (firmware/board/compal_e88/<app>.highram.elf)
# =============================================================================
set -uo pipefail
cd "$(dirname "$(readlink -f "$0")")/../.."
REPO="$(pwd)"
OUT="${1:-kconfig/start/generated}"
GSM_ROOT="${GSM_ROOT:-/opt/GSM}"
RUN_ROOT="${RUN_ROOT:-$GSM_ROOT/${CALYPSO_FORK:-qosmo}}"
FW_DIR="${FIRMWARE_DIR:-$GSM_ROOT/firmware}/board/compal_e88"
C54X_DIR="${C54X_DIR:-$GSM_ROOT/c54x_exe}"
mkdir -p "$OUT"

BUILD_CONFIG=""
for f in "${OSMO_BUILD_CONFIG:-}" /etc/osmocom/build.config "$REPO/.config"; do
    [ -n "$f" ] && [ -r "$f" ] && { BUILD_CONFIG="$f"; break; }
done
yn() { if "$@" >/dev/null 2>&1; then echo y; else echo n; fi; }
built() {   # built SYMBOL -> y|n
    [ -n "$BUILD_CONFIG" ] || { echo y; return; }
    if grep -qx "CONFIG_$1=y" "$BUILD_CONFIG"; then echo y
    elif grep -qx "# CONFIG_$1 is not set" "$BUILD_CONFIG"; then echo n
    else echo y; fi   # unknown to that build (older .config): assumed built
}
have() { yn command -v "$1"; }
file() { yn test -e "$1"; }
q() { local s="$1"; echo "\"${s//\"/\\\"}\""; }

# ── Kconfig.build ────────────────────────────────────────────────────────────
{
    echo "# GENERATED by kconfig/start/gen-start.sh - do not edit"
    echo
    if [ -n "$BUILD_CONFIG" ]; then
        echo "comment $(q "Build : $BUILD_CONFIG ($(sed -n 's/^CONFIG_TARGET="\(.*\)"/\1/p' "$BUILD_CONFIG" | head -1), $(sed -n 's/^CONFIG_ARCH="\(.*\)"/\1/p' "$BUILD_CONFIG" | head -1))")"
    else
        echo 'comment "Build : aucun .config trouve, tout est suppose construit"'
    fi
    for s in GAPK SMSC SMS_CODING_UTILS TRANSCEIVER BURST_IND GRGSM_EXE GNURADIO LTE PMBOOTSTRAP \
             EGPRS_WEB TNCATTACH RNS; do
        echo "config BUILT_$s"; echo "	def_bool $(built "FEAT_$s")"
    done
    # START_DEFAULT_* of the build: the defaults of this menu.
    for s in ISOLATION MULTITHREADING; do
        v="$(built "START_DEFAULT_$s")"; echo "config BUILD_DEFAULT_$s"; echo "	def_bool $v"
    done
    while read -r sym test; do
        echo "config HAVE_$sym"; echo "	def_bool $(eval "$test")"
    done <<EOF
C54X_EXE file $C54X_DIR/c54x_exe
ISOLER file $C54X_DIR/isoler.sh
GRGSM_EXE file $GSM_ROOT/grgsm_exe
TRX_FW file $FW_DIR/trx.highram.elf
LAYER1_FW file $FW_DIR/layer1.highram.elf
TRANSCEIVER have transceiver
MAGNETITE file ${MAGNETITE_FLASH:-$GSM_ROOT/firmware/magnetite/c139-flash.img}
CCCH_SCAN have ccch_scan
BCCH_SCAN have bcch_scan
CELL_LOG have cell_log
VIRTPHY have virtphy
BTS_VIRTUAL have osmo-bts-virtual
TRXCON have trxcon
MOBILE have mobile
FAKE_TRX file ${OSMOCOM_BB:-$GSM_ROOT/osmocom-bb}/src/target/trx_toolkit/fake_trx.py
SOFTSIM file $GSM_ROOT/softsim
GAPK have osmo-gapk
TNCATTACH have tncattach
RNS file /root/.env/bin/rnodeconf
GTK yn /usr/bin/python3 -c "import gi"
DOCKER have docker
START_DOCKER file $REPO/launch/start-docker.sh
VBOX have VBoxManage
EOF
} >"$OUT/Kconfig.build"

# ── Kconfig.params: globals.conf, defaults = the build's values ─────────────
bash "$REPO/kconfig/gen-params.sh" start "$OUT/Kconfig.params" "$BUILD_CONFIG"

# ── Kconfig.runmods ──────────────────────────────────────────────────────────
# Infrastructure (no sense without it) -> selected, shown -*-. The Calypso
# chain (qemu, pty, osmocon, l2) is run.sh's only in --grgsm: in DSP mode
# c54x_exe/run.sh takes it over. Side-car and modem follow their switches.
INFRA=" prereqs outils rundir config logs teardown reseau "
CHAIN=" qemu pty osmocon l2 "
SIDECAR=" sidecar-cfg sidecar-faketrx sidecar-bts sidecar-pcu sidecar-trxcon sidecar-mobile modem-trxcon modem-gprs "
MODEM=" modem-trxcon modem-gprs sidecar-pcu "
# run.sh modules that need a component of the build
declare -A RM_BUILT=([smsc]=BUILT_SMSC [audio]=BUILT_GAPK)
declare -A RM_DESC RM_DEPS; RM_ORDER=()
for f in "$RUN_ROOT"/run_modules/[0-9][0-9]-*.sh; do
    [ -r "$f" ] || continue
    slug="$(sed -n 's/^MOD_REGISTER \([^ ]*\) .*/\1/p' "$f" | head -1)"; [ -n "$slug" ] || continue
    RM_DESC[$slug]="$(sed -n 's/^MOD_REGISTER [^ ]* "\(.*\)".*/\1/p' "$f" | head -1)"
    RM_DEPS[$slug]="$(sed -n "s/^MOD_DEPS\[$slug\]=\"\(.*\)\"/\1/p" "$f" | head -1)"
    RM_ORDER+=("$slug")
done
rsym() { local u="${1^^}"; echo "RUN_MOD_${u//-/_}"; }
# Depth-first: a module, then those depending on it (mconf nests them).
_rm_done=" "; RM_TREE=()
_rm_visit() {
    local x="$1" y d ok
    _rm_done="$_rm_done$x "; RM_TREE+=("$x")
    for y in "${RM_ORDER[@]}"; do
        [[ "$_rm_done" == *" $y "* ]] && continue
        [[ " ${RM_DEPS[$y]} " == *" $x "* ]] || continue
        ok=1; for d in ${RM_DEPS[$y]}; do [ -n "${RM_DESC[$d]:-}" ] && [[ "$_rm_done" != *" $d "* ]] && ok=0; done
        [ "$ok" = 1 ] && _rm_visit "$y"
    done
}
for m in "${RM_ORDER[@]}"; do [[ "$_rm_done" == *" $m "* ]] || _rm_visit "$m"; done
{
    echo "# GENERATED by kconfig/start/gen-start.sh from $RUN_ROOT/run_modules - do not edit"
    echo
    [ "${#RM_ORDER[@]}" -gt 0 ] || echo "comment \"run_modules introuvables dans $RUN_ROOT\""
    echo "config RUN_MOD_INFRA"; echo "	def_bool LAUNCH_NATIVE"
    for m in $INFRA; do [ -n "${RM_DESC[$m]:-}" ] && echo "	select $(rsym "$m")"; done
    echo
    for m in "${RM_TREE[@]}"; do
        s="$(rsym "$m")"
        echo "config $s"
        if [[ "$INFRA" == *" $m "* ]]; then echo "	bool $(q "$m : ${RM_DESC[$m]}")"
        else echo "	bool $(q "$m : ${RM_DESC[$m]}")"; echo "	default y"; fi
        echo "	depends on LAUNCH_NATIVE"
        d=""; for x in ${RM_DEPS[$m]}; do [ -n "${RM_DESC[$x]:-}" ] && d="${d:+$d && }$(rsym "$x")"; done
        [ -n "$d" ] && echo "	depends on $d"
        [[ "$CHAIN" == *" $m "* ]] && echo "	depends on L1_GRGSM"
        [[ "$SIDECAR" == *" $m "* ]] && echo "	depends on SIDECAR"
        [[ "$MODEM" == *" $m "* ]] && echo "	depends on MODEM_GPRS"
        [ -n "${RM_BUILT[$m]:-}" ] && echo "	depends on ${RM_BUILT[$m]}"
        echo "	help"
        echo "	  Module '$m' de $RUN_ROOT/run.sh (run_modules/)."
        [ -n "${RM_DEPS[$m]}" ] && echo "	  Apres : ${RM_DEPS[$m]}."
        [[ "$CHAIN" == *" $m "* ]] && echo "	  En mode DSP, la chaine Calypso est celle de c54x_exe/run.sh."
        echo "	  Decoche : run.sh --skip $m."
        echo
    done
} >"$OUT/Kconfig.runmods"

# ── Kconfig.firmware: the firmware of the emulated phone (a whole choice) ───
{
    echo "# GENERATED by kconfig/start/gen-start.sh from $FW_DIR - do not edit"
    echo
    echo 'choice'
    echo '	prompt "Firmware du telephone emule"'
    echo '	depends on LAUNCH_NATIVE && (!BTS_CALYPSO_TRX || MS_AIR)'
    echo '	default FW_LAYER1'
    echo '	help'
    echo '	  Ce qui tourne sur l ARM du Calypso emule (le MS#1, ou le mobile'
    echo '	  par l air en --bts). Les choix viennent des firmwares presents.'
    echo
    echo 'config FW_LAYER1'
    echo '	bool "layer1 osmocom-bb + un client de couche 2 sur l hote"'
    echo '	depends on HAVE_LAYER1_FW'
    echo
    echo 'config FW_MAGNETITE'
    echo '	bool "FreeCalypso Magnetite (C139, firmware TI complet) (--ms-magnetite)"'
    echo '	depends on HAVE_MAGNETITE && L1_DSP'
    echo '	help'
    echo '	  Le vrai firmware TI en flash (MAGNETITE_FLASH) : pile L23 et'
    echo '	  interface dans le firmware, pas d osmocon ni de mobile ; voix'
    echo '	  toujours par la ROM. doc/magnetite.md.'
    echo
    apps=()
    for f in "$FW_DIR"/*.highram.elf; do
        [ -r "$f" ] || continue
        a="$(basename "$f" .highram.elf)"
        case "$a" in layer1|trx|loader) continue ;; esac
        apps+=("$a"); u="${a^^}"; u="${u//-/_}"
        echo "config FW_APP_$u"
        echo "	bool $(q "appli $a seule (FIRMWARE_APP=$a, sans mobile)")"
        echo "	depends on L1_DSP && !BTS_CALYPSO_TRX"
        echo "	help"
        echo "	  $f seule sur l'ARM, avec le DSP : etapes 1-3 de"
        echo "	  c54x_exe/run.sh, ni mobile ni pont. Ecran et clavier du C123"
        echo "	  emules (Fenetre du telephone)."
        echo
    done
    echo 'endchoice'
    echo
    echo 'config FIRMWARE_APP'
    echo '	string'
    for a in "${apps[@]}"; do u="${a^^}"; u="${u//-/_}"; echo "	default \"$a\" if FW_APP_$u"; done
    echo '	default ""'
} >"$OUT/Kconfig.firmware"
