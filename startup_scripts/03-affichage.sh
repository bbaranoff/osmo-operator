# 03-affichage.sh - part of start.sh (display helpers, globals.conf)
# Sourced by start.sh in the main shell: same order, same variables.
say_begin() {
    if [ $TTY -eq 1 ]; then
        printf '[ %s.. %s] %s' "$C_DIM" "$C_Z" "$1"
    else
        printf '[ .. ] %s\n' "$1"
    fi
}
say_end() { # $1=tag $2=color $3=label $4=detail
    if [ $TTY -eq 1 ]; then printf '\r\033[K'; fi
    printf '[%s%s%s] %s' "$2" "$1" "$C_Z" "$3"
    [ -n "${4:-}" ] && printf ' %s(%s)%s' "$C_DIM" "$4" "$C_Z"
    printf '\n'
}
banner() {
    echo -e "${C_CYAN}"
    echo "╔══════════════════════════════════════════════════════╗"
    echo "║   Calypso GSM - bootstrap → run.sh                   ║"
    echo "╚══════════════════════════════════════════════════════╝"
    echo -e "${C_Z}"
}
# --- 0. who may overwrite a configuration -------------------------------------
# A plain start.sh (or --config) NEVER rewrites a configuration file that
# exists: it starts with what is in place. Only start.sh --configure
# (OSMO_CONFIGURE=1, exported by it) rewrites them, and --regen for the
# templates. A missing file is always created (first start).
#
# A file that still carries unfilled template markers (__IMSI__, __KI__,
# __ARFCN__...) is not a configuration, it is a raw template copied in place
# (older ISO builds put configs/mobile.cfg in /root/.osmocom/bb as is): keeping
# it would start a mobile without IMSI/Ki, the HLR could not be provisioned and
# the bench would fail. It is rewritten like a missing file.
conf_ecrasable() {   # conf_ecrasable FILE -> 0 if this start may write FILE
    [ ! -e "$1" ] || [ "${OSMO_CONFIGURE:-0}" = 1 ] || conf_gabarit_brut "$1"
}
conf_gabarit_brut() {  # conf_gabarit_brut FILE -> 0 if FILE has unfilled markers
    # comment lines skipped: the template header lists the markers in prose
    grep -v '^[[:space:]]*[#!]' "$1" 2>/dev/null | grep -qE '__[A-Z][A-Z0-9_]*__'
}
conf_garde() {       # conf_garde FILE WHAT -> says that FILE is kept
    printf '  %sconserve%s   %s (%s ; start.sh --configure pour la reecrire)\n' \
        "${C_DIM:-}" "${C_Z:-}" "$1" "$2"
}

# --- 1. configuration ---------------------------------------------------------
# globals.conf - the network settings (MCC/MNC/ARFCN/KI/IMSI/A5...).
# Generated by ./generate_configs.sh on the host side; here it is only read.
# globals.conf does not use the ":=" idiom but plain assignment
# (`ENCRYPTION="a5 1"`) and is sourced with `set -a`: it OVERWRITES the
# environment (its own header says so: read last, its settings overwrite
# their namesake in the environment).
#
# The command line wins, as everywhere else in this script: the globals.conf
# variables that the caller has ALREADY set and non-empty are noted, the file
# is read, then they are set again. globals.conf stays the reference for
# everything not said; an empty value still means "computed value", so it
# overrides nothing.
# The SQL base (tools/osmo-db.py) follows the configuration files: re-read
# here, before the start (only what changed; nothing is written but the base).
python3 "$HERE/tools/osmo-db.py" sync --quiet 2>/dev/null || true
# stick of the mobiles = ARFCN of a BTS of osmo-bsc.cfg (start.sh no longer
# rewrites them: a mismatch is said, start.sh --configure realigns everything).
python3 "$HERE/tools/osmo-db.py" coherence 2>/dev/null | sed "s/^/  ${C_KO:-}!!${C_Z:-} /" || true
if [ -r "$HERE/globals.conf" ]; then
    _gc_forcees=()
    while IFS= read -r _gc_v; do
        [ -n "${!_gc_v:-}" ] && _gc_forcees+=("$_gc_v=${!_gc_v}")
    done < <(sed -n 's/^\([A-Za-z_][A-Za-z0-9_]*\)=.*/\1/p' "$HERE/globals.conf")
    set -a
    . "$HERE/globals.conf"
    for _gc_kv in "${_gc_forcees[@]}"; do
        eval "${_gc_kv%%=*}=\${_gc_kv#*=}"
    done
    set +a
    [ ${#_gc_forcees[@]} -gt 0 ] && \
        printf '  %sglobals.conf%s surcharge par l environnement : %s\n' \
            "${C_DIM:-}" "${C_Z:-}" "${_gc_forcees[*]}"
    unset _gc_v _gc_kv
fi

