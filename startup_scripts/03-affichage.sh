# 03-affichage.sh - part of start.sh (display helpers, globals.conf)
# Sourced by start.sh in the main shell: same order, same variables.
say_begin() {
    if [ $TTY -eq 1 ]; then
        printf '[ %s.. %s] %s' "$C_DIM" "$C_Z" "$1"
    else
        printf '[ .. ] %s\n' "$1"
    fi
}
say_end() { # $1=tag $2=color $3=label $4=detail
    if [ $TTY -eq 1 ]; then printf '\r\033[K'; fi
    printf '[%s%s%s] %s' "$2" "$1" "$C_Z" "$3"
    [ -n "${4:-}" ] && printf ' %s(%s)%s' "$C_DIM" "$4" "$C_Z"
    printf '\n'
}
banner() {
    echo -e "${C_CYAN}"
    echo "╔══════════════════════════════════════════════════════╗"
    echo "║   Calypso GSM - bootstrap → run.sh                   ║"
    echo "╚══════════════════════════════════════════════════════╝"
    echo -e "${C_Z}"
}
# --- 1. configuration ---------------------------------------------------------
# globals.conf - the network settings (MCC/MNC/ARFCN/KI/IMSI/A5...).
# Generated by ./generate_configs.sh on the host side; here it is only read.
# globals.conf does not use the ":=" idiom but plain assignment
# (`ENCRYPTION="a5 1"`) and is sourced with `set -a`: it OVERWRITES the
# environment (its own header says so: read last, its settings overwrite
# their namesake in the environment).
#
# The command line wins, as everywhere else in this script: the globals.conf
# variables that the caller has ALREADY set and non-empty are noted, the file
# is read, then they are set again. globals.conf stays the reference for
# everything not said; an empty value still means "computed value", so it
# overrides nothing.
if [ -r "$HERE/globals.conf" ]; then
    _gc_forcees=()
    while IFS= read -r _gc_v; do
        [ -n "${!_gc_v:-}" ] && _gc_forcees+=("$_gc_v=${!_gc_v}")
    done < <(sed -n 's/^\([A-Za-z_][A-Za-z0-9_]*\)=.*/\1/p' "$HERE/globals.conf")
    set -a
    . "$HERE/globals.conf"
    for _gc_kv in "${_gc_forcees[@]}"; do
        eval "${_gc_kv%%=*}=\${_gc_kv#*=}"
    done
    set +a
    [ ${#_gc_forcees[@]} -gt 0 ] && \
        printf '  %sglobals.conf%s surcharge par l environnement : %s\n' \
            "${C_DIM:-}" "${C_Z:-}" "${_gc_forcees[*]}"
    unset _gc_v _gc_kv
fi

