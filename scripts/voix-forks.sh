#!/bin/bash
# =============================================================================
#  scripts/voix-forks.sh - the two voice settings that live in the forks
# =============================================================================
#
#  The bench voice depends on two lines that are not in osmo-operator: they are
#  in qosmo (run_modules, cfgs), a repository that the update resynchronises
#  with « git reset --hard FETCH_HEAD ». Any fix applied by hand in those trees
#  disappears at the next start. They are therefore reapplied, after each
#  fetch, from here - this file is the only one that knows how.
#
#  1. « io-tch-format rtp » in cfgs/mobile_group1.cfg.
#     This is the template that run.sh (run_modules/20-mobile-cfg.sh) copies
#     over ~/.osmocom/bb/mobile_group1.cfg at each start - it overwrites what
#     start-native.sh generated. Without this line the mobile reads and writes
#     its TCH frames in the Texas Instruments layout of real Calypsos, while
#     pont.py codes them with libosmocoding, i.e. in the RTP/RFC3551 layout
#     (33 bytes opened by the 0xD signature). Neither side understands the
#     other, no counter complains, and the voice comes out robotic.
#
#  2. CALYPSO_PULSE_LATENCY_MSEC in run_modules/70-l2.sh and
#     68-sidecar-mobile.sh. The mobile writes one GSM frame (160 samples,
#     20 ms) per snd_pcm_writei; if the ALSA-PulseAudio plugin buffer is too
#     short, each write returns -EPIPE, and pq_alsa.c answers with a silent
#     snd_pcm_prepare() that tears down and rebuilds the PulseAudio stream.
#     Measured with a writer paced at 20 ms like the mobile, over 10 s:
#         80 ms -> 16 rebuilds   120 -> 19   160 -> 1   200 -> 0   240 -> 0
#     During a real call: 50 per second. start-native.sh exports 320, which is
#     enough; the fork default is aligned for whoever runs run.sh alone.
#
#  Callers: update.sh (osmo_poser_voix_forks), the osmo-update service
#  generated by iso_modules/81-cloture-systeme.sh (right after the fetch), and
#  iso_modules/70-scripts.sh (on the ROOTFS, when building the ISO).
#
#  Usage: voix-forks.sh [prefix]     (prefix = a ROOTFS, empty by default)
#  Idempotent, no effect if the forks are absent, always exit 0.
#
#  Check: `grep io-tch-format ~/.osmocom/bb/mobile_group1.cfg` after a start;
#  and during an established call, the sink-input index of the mobile must stay
#  fixed (`pactl list short sink-inputs`, two readings 1 s apart).
# -----------------------------------------------------------------------------
set -u
ROOT="${1:-}"
VOIX_LATENCE="${CALYPSO_PULSE_LATENCY_MSEC_DEFAUT:-320}"
VOIX_TCH_FORMAT="${MS_TCH_FORMAT:-rtp}"

voix_forks_poser() {
    local f n fait=0
    for f in "$ROOT/opt/GSM/qosmo/cfgs/mobile_group1.cfg"; do
        [ -f "$f" ] || continue
        grep -q '^[[:space:]]*io-tch-format' "$f" && continue
        # Right after « io-handler », in the tch-voice block, same indentation.
        if sed -i '/^[[:space:]]*tch-voice[[:space:]]*$/,/^[[:space:]]*no shutdown/ s/^\([[:space:]]*\)io-handler\(.*\)$/\1io-handler\2\n\1io-tch-format '"$VOIX_TCH_FORMAT"'/' "$f" \
           && grep -q "io-tch-format ${VOIX_TCH_FORMAT}" "$f"; then
            echo "  [voix] ${f#"$ROOT"} : io-tch-format ${VOIX_TCH_FORMAT} repose (voix robotisee sinon)"; fait=1
        else
            echo "  [voix] ${f#"$ROOT"} : io-tch-format NON pose - a regarder a la main" >&2
        fi
    done
    for f in "$ROOT/opt/GSM/qosmo/run_modules/70-l2.sh" \
             "$ROOT/opt/GSM/qosmo/run_modules/68-sidecar-mobile.sh"; do
        [ -f "$f" ] || continue
        n="$(sed -n 's/^: "${CALYPSO_PULSE_LATENCY_MSEC:=\([0-9]*\)}"/\1/p' "$f" | head -1)"
        [ -n "$n" ] || continue
        [ "$n" -ge "$VOIX_LATENCE" ] 2>/dev/null && continue
        sed -i "s|^: \"\${CALYPSO_PULSE_LATENCY_MSEC:=[0-9]*}\"|: \"\\\${CALYPSO_PULSE_LATENCY_MSEC:=${VOIX_LATENCE}}\"|" "$f" \
            && { echo "  [voix] ${f#"$ROOT"} : tampon du mobile ${n} -> ${VOIX_LATENCE} ms (flux PulseAudio remonte sinon)"; fait=1; }
    done
    return 0
}
voix_forks_poser
exit 0
